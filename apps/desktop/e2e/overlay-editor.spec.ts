import { expect, test } from '@playwright/test';
import { completeFirstRunFixture } from './fixtures/first-run-page';

for (const width of [1120, 800]) test(`overlay editor supports drag, keyboard positioning and reset at ${width}px`, async ({ page }, testInfo) => {
 await page.setViewportSize({ width, height: 1000 });
 await completeFirstRunFixture(page);
 await page.getByRole('button', { name: 'Настройки', exact: true }).click();
 await page.getByTestId('runtime-settings').getByRole('radio', { name: 'Приложение', exact: true }).click();
 await expect(page.getByLabel('Редактор оверлея', { exact: true })).toHaveCount(0);
 await page.getByTestId('runtime-settings').getByRole('radio', { name: 'Оверлей и уведомления', exact: true }).click();
 await expect(page.getByTestId('apply-settings-button')).toHaveCount(0);
 await page.getByRole('button', { name: 'Настроить оверлей', exact: true }).click();
 await expect(page.getByRole('dialog', { name: 'Конструктор оверлея' })).toBeVisible();
 const canvas = page.getByLabel('Редактор оверлея', { exact: true });
 await canvas.scrollIntoViewIfNeeded();
 const recording = canvas.getByRole('button', { name: 'Статус записи' });
 const replay = canvas.getByRole('button', { name: 'Статус повтора' });
 const replayPosition = await replay.getAttribute('style');
 const before = await recording.boundingBox();
 expect(before!.width).toBe(30);
 const dialogBox = await page.getByRole('dialog', { name: 'Конструктор оверлея' }).boundingBox();
 expect(dialogBox!.width).toBe(width);
 expect(dialogBox!.height).toBe(1000);
 const area = await canvas.boundingBox();
 await page.mouse.move(before!.x + before!.width / 2, before!.y + before!.height / 2);
 await page.mouse.down();
 await page.mouse.move(area!.x + area!.width / 2, area!.y + area!.height / 2, { steps: 12 });
 await page.mouse.up();
 const after = await recording.boundingBox();
 expect(after!.x).toBeLessThan(before!.x - 40);
 expect(after!.y).toBeLessThan(before!.y - 40);
 expect(await replay.getAttribute('style')).toBe(replayPosition);
 await recording.press('ArrowLeft');
 expect((await recording.boundingBox())!.x).toBeLessThan(after!.x);
 await expect(page.getByRole('dialog').getByRole('button')).toHaveCount(3);
 await expect(canvas.getByRole('button', { name: 'Сообщения' })).toBeVisible();
 await page.screenshot({ path: testInfo.outputPath('overlay-editor.png') });
 await page.getByRole('dialog').press('Control+Backspace');
 expect((await recording.boundingBox())!.x).toBeCloseTo(before!.x, 0);
 await page.getByRole('dialog').press('Control+Enter');
 await expect(page.getByRole('dialog').getByRole('status')).toHaveText('Оверлей сохранён');
 await expect(page.getByRole('dialog')).toHaveAttribute('data-feedback', 'saved');
 await expect(page.getByRole('dialog', { name: 'Конструктор оверлея' })).toHaveCount(0);
 await page.getByRole('button', { name: 'Настроить оверлей', exact: true }).click();
 const saved = await recording.getAttribute('style');
 await recording.press('ArrowLeft');
 await page.getByRole('dialog', { name: 'Конструктор оверлея' }).press('Escape');
 await expect(page.getByRole('dialog', { name: 'Конструктор оверлея' })).toHaveCount(0);
 await page.getByRole('button', { name: 'Настроить оверлей', exact: true }).click();
 expect(await recording.getAttribute('style')).toBe(saved);
 await page.getByRole('dialog').press('Escape');
 await expect(page.getByRole('dialog').getByRole('status')).toHaveText('Изменения отменены');
 await expect(page.getByRole('dialog')).toHaveAttribute('data-feedback', 'cancelled');
 await expect(page.getByRole('dialog')).toHaveCount(0);
});
for (const [width, height] of [[1920, 1080], [2560, 1080], [1280, 720]]) test(`preview matches runtime element size and position at ${width}x${height}`, async ({ page }) => {
 await page.route('**/overlay-geometry?*', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><html><body><div id="root"></div><script type="module">import RefreshRuntime from '/@react-refresh';RefreshRuntime.injectIntoGlobalHook(window);window.$RefreshReg$=()=>{};window.$RefreshSig$=()=>type=>type;window.__vite_plugin_react_preamble_installed__=true;</script><script type="module" src="/e2e/fixtures/overlay-geometry.tsx"></script></body></html>` }));
 await page.goto(`/overlay-geometry?width=${width}&height=${height}`);
 await expect(page.getByLabel('Редактор оверлея')).toBeVisible();
 await page.evaluate(() => document.fonts.ready);
 const comparison = await page.evaluate(() => {
  const canvas = document.querySelector('[data-overlay-stage]')!.parentElement!;
  const stage = document.querySelector('[data-overlay-stage]')!;
  const runtime = document.querySelector('[data-runtime]')!;
  const a = stage.getBoundingClientRect(); const b = runtime.getBoundingClientRect();
  const scale = a.width / b.width;
  const compare = (label: string, selector: string) => {
   const preview = canvas.querySelector(`button[aria-label="${label}"]`)!.getBoundingClientRect();
   const actual = runtime.querySelector(selector)!.getBoundingClientRect();
   return { preview: [preview.x-a.x, preview.y-a.y, preview.width, preview.height], expected: [(actual.x-b.x)*scale, (actual.y-b.y)*scale, actual.width*scale, actual.height*scale] };
  };
  return [compare('Статус записи', '[data-runtime-recording]'), compare('Статус повтора', '[data-runtime-replay]'), compare('Сообщения', '[data-runtime-notification]')];
 });
 for (const item of comparison) item.preview.forEach((coordinate, index) => expect(Math.abs(coordinate-item.expected[index])).toBeLessThan(.5));
});
